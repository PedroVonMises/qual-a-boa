/** States open in the pilot. Everything else shows "Em breve". */
export const PILOT_UFS: readonly Uf[] = ['ES'];

export const DEFAULT_UF: Uf = 'ES';

export const isUf = (v: unknown): v is Uf => typeof v === 'string' && REGIONS.some((r) => r.uf === v);

export const isPilotUf = (v: unknown): v is Uf => isUf(v) && PILOT_UFS.includes(v);

/** "Espírito Santo" for 'ES'; the code itself for anything unknown. */
export function ufName(uf: string): string {
  return REGIONS.find((r) => r.uf === uf)?.name ?? uf;
}
