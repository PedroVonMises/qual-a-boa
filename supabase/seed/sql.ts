/**
 * Render a SeedDataset as idempotent Postgres UPSERT statements.
 * Safe to execute repeatedly against the same database with zero duplicates and zero data loss.
 */
import type { SeedDataset } from '../../app/src/domain/types';

const q = (v: string | null | undefined): string =>
  v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`;
const n = (v: number | null | undefined): string =>
  v === null || v === undefined ? 'null' : String(v);
const b = (v: boolean): string => (v ? 'true' : 'false');
const arr = (vs: string[]): string =>
  vs.length === 0 ? `'{}'::text[]` : `array[${vs.map(q).join(', ')}]::text[]`;

export function datasetToSql(ds: SeedDataset): string {
  const out: string[] = [];
  out.push(`-- Generated by supabase/seed/build.ts at ${ds.generatedAt}. IDEMPOTENT UPSERT SEED.`);
  out.push('-- Do not edit by hand: run `npm run seed` in app/.');
  out.push('begin;');

  out.push('insert into public.genres (id, slug, label, sort_order) values');
  out.push(
    ds.genres.map((g, i) => `  (${q(g.id)}, ${q(g.slug)}, ${q(g.label)}, ${i})`).join(',\n') +
      '\non conflict (id) do update set slug = excluded.slug, label = excluded.label, sort_order = excluded.sort_order;',
  );

  out.push('insert into public.venues (id, slug, name, area, city, uf, address, lat, lng, status, adult_only, genre_slugs, hours, cover_key, placeholder, access_tags, price_range, image_url, updated_at) values');
  out.push(
    ds.venues
      .map((v) =>
        `  (${q(v.id)}, ${q(v.slug)}, ${q(v.name)}, ${q(v.area)}, ${q(v.city)}, ${q(v.uf ?? 'ES')}, ${q(v.address)}, ${n(v.lat)}, ${n(v.lng)}, ${q(v.status)}, ${b(v.adultOnly)}, ${arr(v.genreSlugs)}, ${q(v.hours)}, ${q(v.coverKey)}, ${b(v.placeholder)}, ${arr(v.accessTags ?? [])}, ${q(v.priceRange ?? '$$')}, ${q(v.imageUrl)}, ${q(v.updatedAt ?? ds.generatedAt)})`,
      )
      .join(',\n') +
      '\non conflict (id) do update set' +
      ' slug = excluded.slug, name = excluded.name, area = excluded.area, city = excluded.city, uf = excluded.uf,' +
      ' address = excluded.address, lat = excluded.lat, lng = excluded.lng, status = excluded.status,' +
      ' adult_only = excluded.adult_only, genre_slugs = excluded.genre_slugs, hours = excluded.hours,' +
      ' cover_key = excluded.cover_key, placeholder = excluded.placeholder, access_tags = excluded.access_tags,' +
      ' price_range = excluded.price_range, image_url = excluded.image_url, updated_at = excluded.updated_at;',
  );

  if (ds.artists.length) {
    out.push('insert into public.artists (id, slug, name, genre_slugs, photo_url) values');
    out.push(
      ds.artists
        .map((a) => `  (${q(a.id)}, ${q(a.slug)}, ${q(a.name)}, ${arr(a.genreSlugs)}, ${q(a.photoUrl)})`)
        .join(',\n') +
        '\non conflict (id) do update set slug = excluded.slug, name = excluded.name, genre_slugs = excluded.genre_slugs, photo_url = excluded.photo_url;',
    );
  }

  out.push('insert into public.events (id, venue_id, title, starts_at, ends_at, price_min, price_max, is_free, ticket_url, age_min, status, cover_key, image_url, popularity, access_tags) values');
  out.push(
    ds.events
      .map((e) =>
        `  (${q(e.id)}, ${q(e.venueId)}, ${q(e.title)}, ${q(e.startsAt)}, ${q(e.endsAt)}, ${n(e.priceMin)}, ${n(e.priceMax)}, ${b(e.isFree)}, ${q(e.ticketUrl)}, ${n(e.ageMin)}, ${q(e.status)}, ${q(e.coverKey)}, ${q(e.imageUrl)}, ${n(e.popularity)}, ${arr(e.accessTags ?? [])})`,
      )
      .join(',\n') +
      '\non conflict (id) do update set' +
      ' venue_id = excluded.venue_id, title = excluded.title, starts_at = excluded.starts_at, ends_at = excluded.ends_at,' +
      ' price_min = excluded.price_min, price_max = excluded.price_max, is_free = excluded.is_free,' +
      ' ticket_url = excluded.ticket_url, age_min = excluded.age_min, status = excluded.status,' +
      ' cover_key = excluded.cover_key, image_url = excluded.image_url, popularity = excluded.popularity,' +
      ' access_tags = excluded.access_tags, updated_at = now();',
  );

  const eg = ds.events.flatMap((e) => e.genreSlugs.map((g) => `  (${q(e.id)}, ${q(g)})`));
  if (eg.length) {
    out.push('insert into public.event_genres (event_id, genre_slug) values');
    out.push(eg.join(',\n') + '\non conflict (event_id, genre_slug) do nothing;');
  }

  const ea = ds.events.flatMap((e) => e.artistIds.map((a, i) => `  (${q(e.id)}, ${q(a)}, ${i})`));
  if (ea.length) {
    out.push('insert into public.event_artists (event_id, artist_id, billing_order) values');
    out.push(ea.join(',\n') + '\non conflict (event_id, artist_id) do update set billing_order = excluded.billing_order;');
  }

  out.push('commit;');
  return out.join('\n') + '\n';
}

export const datasetToUpsertSql = datasetToSql;
